def reliability():
    sec = section(TXT, "A")
    pat = re.compile(r"^  (\S.*?) \[(.*?)\]\s+(\d+)\s+(\S+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+|nan)"
                     r"\s+([\d.]+)\s+(-?\d+)%", re.M)
    rows = pat.findall(sec)
    icc, alpha = rows[:len(rows) // 2], rows[len(rows) // 2:]
    assert len(icc) == len(alpha) == 7, len(rows)
    body = ["\\begin{tabular}{@{}llr ccccc ccccc@{}}", "\\toprule",
            " & & & \\multicolumn{5}{c}{ICC(3,1)} & \\multicolumn{5}{c}{Krippendorff's $\\alpha$} \\\\",
            "\\cmidrule(lr){4-8}\\cmidrule(l){9-13}",
            "Model & Window & $n$ & Raw & Resid & Hold & Chg & Drop & Raw & Resid & Hold & Chg & Drop \\\\",
            "\\midrule"]
    for i, (a, b) in enumerate(zip(icc, alpha)):
        name, path, n, win = a[0], a[1], a[2], a[3]
        win = win.replace("..", "--")
        label = MODELNAME.get(name, name)
        if i == 4:
            body.append("\\addlinespace")
        if i == 5:
            body.append("\\addlinespace\\multicolumn{13}{@{}l}{\\emph{Full corpus (statements with all five prompts)}}\\\\")
        body.append(f"{label} & {win} & {n} & " + " & ".join(a[4:8]) + f" & {a[8]}\\% & "
                    + " & ".join(b[4:8]) + f" & {b[8]}\\% \\\\")
        key = {"changes.csv": "gem", "changes_claude.csv": "haiku", "changes_openai.csv": "mini",
               "changes_frontier.csv": "fable", "changes_2004.csv": "gem04",
               "full_gemini.csv": "gemfull", "scores_fable.csv": "fablefull"}[path]
        for j, col in enumerate(("raw", "resid", "hold", "chg")):
            put(f"icc.{key}.{col}", a[4 + j])
            put(f"alpha.{key}.{col}", b[4 + j])
        put(f"icc.{key}.drop", a[8] + "\\%")
        put(f"alpha.{key}.drop", b[8] + "\\%")
        put(f"icc.{key}.n", n)
    body.insert(6, "\\multicolumn{13}{@{}l}{\\emph{Crossed block: same statements, five prompts, four models}}\\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    write("tab_reliability.tex", "\n".join(body) + "\n")
    m = re.search(r"test-retest: (\d+) cells scored in two runs, r = ([\d.]+), mean \|diff\| = ([\d.]+), (\d+) differ", sec)
    put("retest.n", m.group(1))
    put("retest.r", m.group(2))
    put("retest.mad", m.group(3))
    put("retest.differ", m.group(4))
    # variance decomposition
    vp = re.compile(r"^  (levels|changes), (raw|std in model)\s+(\d+)\s+" + r"\s+".join([r"([\d.]+)%"] * 7), re.M)
    vrows = vp.findall(sec)
    assert len(vrows) == 4
    m = re.search(r"decomposition, (\d+) statements \((\S+)\) x (\d+) prompts x (\d+) models", sec)
    put("var.n", m.group(1))
    body = ["\\begin{tabular}{@{}llr rrrrrrr@{}}", "\\toprule",
            "Data & Scaling & $n$ & Statement & Prompt & Model & S$\\times$P & S$\\times$M & P$\\times$M & Residual \\\\",
            "\\midrule"]
    for kind, scale, n, *sh in vrows:
        body.append(f"{kind.capitalize()} & {'raw' if scale == 'raw' else 'std.\\ within model'} & {n} & "
                    + " & ".join(sh) + " \\\\")
        k = f"var.{kind}.{'raw' if scale == 'raw' else 'std'}"
        for nm, v in zip(("stmt", "prompt", "model", "sxp", "sxm", "pxm", "resid"), sh):
            put(f"{k}.{nm}", v + "\\%")
    body += ["\\bottomrule", "\\end{tabular}"]
    write("tab_variance.tex", "\n".join(body) + "\n")
    return icc


