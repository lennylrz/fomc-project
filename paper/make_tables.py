def yields_check():
    """yields.csv against the FRED DGS2/DGS10 downloads, to the hundredth."""
    y = {r["date"]: r for r in csv.DictReader(open("yields.csv"))}
    match = total = 0
    first = last = None
    for col, fn in (("y2", "fred_DGS2.csv"), ("y10", "fred_DGS10.csv")):
        for r in csv.DictReader(open(fn)):
            d = r.get("observation_date") or r.get("DATE")
            v = r.get("DGS2") if col == "y2" else r.get("DGS10")
            if d in y and v not in ("", ".", None) and y[d].get(col):
                total += 1
                match += abs(float(v) - float(y[d][col])) < 0.005
                first = min(first or d, d)
                last = max(last or d, d)
    days = total // 2
    assert match == total, (match, total)
    put("fred.days", str(days))
    put("fred.first", first)
    put("fred.last", last)


