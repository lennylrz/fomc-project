def truncated():
    """Replies stored cut at 300 characters, and whether the +-1 scores among
    them agree in sign with the statement's other prompts."""
    import analysis as A
    for lab, path in (("fable", A.FABLE), ("gemini", A.GEMINI)):
        rows = [r for r in csv.DictReader(open(path)) if r.get("raw_reply")]
        cut = [r for r in rows if len(r["raw_reply"]) == 300]
        put(f"trunc.{lab}", str(len(cut)))
        put(f"trunc.{lab}.of", str(len(rows)))
        sc = A.collapse(A.load_cells(path)[0])
        ext, agree = 0, 0
        for r in cut:
            try:
                v = float(r["score"])
            except ValueError:
                continue
            if abs(v) != 1.0 or r["date"] not in sc or (r["date"], r["prompt"], r.get("source")) in A.PARSE_ERRORS:
                continue
            others = [x for p, x in sc[r["date"]].items() if p != r["prompt"]]
            if not others:
                continue
            ext += 1
            agree += (statistics.mean(others) > 0) == (v > 0)
        put(f"trunc.{lab}.ext", str(ext))
        put(f"trunc.{lab}.agree", str(agree))


