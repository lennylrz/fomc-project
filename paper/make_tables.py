def tex(s):
    """Escape plain text for LaTeX."""
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
           "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}
    s = "".join(rep.get(c, c) for c in s)
    s = s.replace("—", "---").replace("–", "--").replace("’", "'").replace("“", "``").replace("”", "''")
    s = re.sub(r'"([^"]*)"', r"``\1''", s)
    return s.replace('"', "''")


def f(x, d=2, sign=False):
    if x is None or x != x:
        return "--"
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def fp(p):
    return "$<$0.001" if p < 0.001 else f(p, 3)


def put(key, val):
    if key in V and V[key] != val:
        raise SystemExit(f"numbers.tex: key {key} set twice ({V[key]} vs {val})")
    V[key] = val


def write(name, body):
    os.makedirs(TAB, exist_ok=True)
    with open(os.path.join(TAB, name), "w") as fh:
        fh.write("% generated by paper/make_tables.py - do not edit\n" + body)


def section(txt, letter):
    """The block of analysis.py output for part <letter>."""
    m = re.search(rf"^{letter}\. .*?$(.*?)(?=^=+\n^[A-Z]+[\. ]|\Z)", txt, re.S | re.M)
    if not m:
        raise SystemExit(f"part {letter} not found")
    return m.group(1)


def load_rows(path):
    out = []
    for r in csv.DictReader(open(path)):
        for k in ("beta", "t_ols", "t_hc1", "t_nw", "p_nw", "r2"):
            r[k] = float(r[k]) if r.get(k) not in (None, "") else float("nan")
        r["p_holm"] = float(r["p_holm"]) if r.get("p_holm") else None
        r["n"] = int(r["n"])
        out.append(r)
    return out


def pick(rows, part, model, y, sample, control="-"):
    hits = [r for r in rows if r["part"] == part and r["model"] == model and r["y"] == y
            and r["sample"] == sample and r["control"] == control]
    if len(hits) != 1:
        raise SystemExit(f"{len(hits)} rows for {part} {model} {y} {sample} {control}")
    return hits[0]


