def corpus():
    types = list(csv.DictReader(open("corpus_types.csv")))
    cnt = {}
    for r in types:
        cnt[r["type"]] = cnt.get(r["type"], 0) + 1
    put("corpus.files", str(len(types)))
    for k, v in cnt.items():
        put("corpus." + k.replace("_", ""), str(v))
    put("corpus.policy", str(len(types) - cnt["notice"]))
    put("corpus.first", types[0]["date"])
    put("corpus.last", types[-1]["date"])
    m = re.search(r"--corpus policy: (\d+) statements", TXT)
    put("corpus.policy.check", m.group(1))
    months = {}
    for r in types:
        if r["date"] < "2024":
            months[r["date"][:7]] = months.get(r["date"][:7], 0) + 1
    put("corpus.multimonth", str(sum(v > 1 for v in months.values())))
    put("corpus.prenotices", str(sum(r["type"] == "notice" and r["date"] < "2024" for r in types)))
    put("corpus.zlbnotices", str(sum(r["type"] == "notice" and "2009-01" <= r["date"][:7] <= "2015-11"
                                     for r in types)))
    lines = []
    for r in types:
        if r["type"] == "scheduled":
            continue
        note = (r["note"].replace("not in surprises.csv", "no MPS in the Bauer--Swanson data")
                .replace("TSLF", "Term Securities Lending Facility")
                .replace("FIMA repo", "repo facility for foreign and international monetary authorities")
                .replace("9/11", "11 September 2001"))
        lines.append(f"{r['date']} & {tex(r['type'].replace('_', ' '))} & {tex(note).replace('Bauer--Swanson', 'Bauer--Swanson')} \\\\")
    write("tab_corpus.tex", "\\begin{tabular}{@{}llp{9cm}@{}}\n\\toprule\nDate & Type & Note \\\\\n\\midrule\n"
          + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")


def descriptives():
    import analysis as A
    statements, policy, market = A.load_market()
    statements, _ = A.corpus_filter(statements, "policy")
    pre = [d for d in statements if d < A.POST_CUTOFF]
    hold = [d for d in pre[1:] if policy[d] == 0]
    put("desc.pre", str(len(pre)))
    put("desc.prepairs", str(len(pre) - 1))
    put("desc.hold", str(len(hold)))
    put("desc.moves", str(sum(policy[d] != 0 for d in pre)))
    put("desc.post", str(sum(d >= A.POST_CUTOFF for d in statements)))
    # prompt coverage per policy statement
    for lab, path in (("fable", A.FABLE), ("gemini", A.GEMINI)):
        sc = A.collapse(A.load_cells(path)[0])
        k = [len(sc.get(d, {})) for d in statements]
        put(f"cover.{lab}.five", str(sum(x == 5 for x in k)))
        put(f"cover.{lab}.fewer", str(sum(0 < x < 5 for x in k)))
        put(f"cover.{lab}.none", str(sum(x == 0 for x in k)))
        put(f"cover.{lab}.prefive", str(sum(x == 5 for x, d in zip(k, statements) if d < A.POST_CUTOFF)))
        put(f"cover.{lab}.prefewer", str(sum(0 < x < 5 for x, d in zip(k, statements) if d < A.POST_CUTOFF)))
        few = [d for x, d in zip(k, statements) if 0 < x < 5]
        if few:
            put(f"cover.{lab}.fewfirst", min(few)[:4])
    rows = []
    for y, lab, unit in (("MPS", "MPS", "pp"), ("MPS_ORTH", "MPS\\_ORTH", "pp"),
                         ("t2", "2-year yield, 30-minute ($t_2$)", "bp"),
                         ("t10", "10-year yield, 30-minute ($t_{10}$)", "bp"),
                         ("d2", "2-year yield, daily ($d_2$)", "bp"),
                         ("d10", "10-year yield, daily ($d_{10}$)", "bp")):
        for samp, use in (("all", pre[1:]), ("hold", hold)):
            v = [market[d][y] for d in use if y in market[d]]
            rows.append((lab if samp == "all" else "", unit, samp, len(v),
                         statistics.mean(v), statistics.stdev(v), min(v), max(v),
                         min(d for d in use if y in market[d])[:4],
                         max(d for d in use if y in market[d])[:4]))
            if samp == "hold":
                put(f"desc.sd.{y}", f(statistics.stdev(v), 3 if y.startswith("MPS") else 1))
                SD[y] = statistics.stdev(v)
                put(f"desc.n.{y}", str(len(v)))
    for a, b in (("t2", "d2"), ("t10", "d10")):
        both = [d for d in pre[1:] if a in market[d] and b in market[d]]
        put(f"desc.corr.{a}.{b}", f(statistics.correlation([market[d][a] for d in both],
                                                          [market[d][b] for d in both])))
    for y in ("t2", "t10"):
        both = [d for d in hold if "MPS" in market[d] and y in market[d]]
        put(f"desc.corr.MPS.{y}", f(statistics.correlation([market[d]["MPS"] for d in both],
                                                            [market[d][y] for d in both])))
    d = 3
    body = ["\\begin{tabular}{@{}llrrrrrrl@{}}", "\\toprule",
            "Outcome & Unit & Sample & $n$ & Mean & SD & Min & Max & Years \\\\", "\\midrule"]
    for lab, unit, samp, n, mu, sd, lo, hi, a, b in rows:
        dd = 3 if unit == "pp" else 1
        body.append(f"{lab} & {unit if lab else ''} & {samp} & {n} & {f(mu, dd)} & {f(sd, dd)} & {f(lo, dd)} & {f(hi, dd)} & {a}--{b} \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    write("tab_desc.tex", "\n".join(body) + "\n")


