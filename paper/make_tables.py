def probe_counts(path):
    rows = [r for r in csv.DictReader(open(path)) if r["err_months"] != ""]
    e = [abs(int(r["err_months"])) for r in rows]
    zlb = [abs(int(r["err_months"])) for r in rows if "2009-01" <= r["date"] <= "2015-11"]
    return {"n": len(e), "exact": sum(x == 0 for x in e), "w1": sum(x <= 1 for x in e),
            "w3": sum(x <= 3 for x in e), "zlbn": len(zlb), "zlb": sum(x == 0 for x in zlb),
            "high": sum(r["confidence"] == "high" for r in rows)}


